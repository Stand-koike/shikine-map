#Requires -Version 5.1
<#
  QGIS から書き出した EPSG:4326 GeoTIFF を Web 用 WebP + config.local.js に変換
  要: OSGeo4W の gdal_translate / gdalinfo が PATH にあること
#>
param(
    [Parameter(Mandatory = $true)]
    [string]$GeoTiff,
    [Parameter(Mandatory = $true)]
    [string]$WebRoot
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $GeoTiff)) { throw "GeoTIFF not found: $GeoTiff" }
if (-not (Get-Command gdalinfo -ErrorAction SilentlyContinue)) {
    throw "gdalinfo not found. Install OSGeo4W and add to PATH."
}

$outWebp = Join-Path $WebRoot "map-qgis.webp"
$outConfig = Join-Path $WebRoot "config.local.js"

# Int16 等は WebP 非対応のため Byte にスケール
& gdal_translate -of WEBP -ot Byte -scale -co QUALITY=90 $GeoTiff $outWebp
$infoJson = Join-Path $env:TEMP ("gdalinfo-" + [Guid]::NewGuid().ToString("n") + ".json")
& gdalinfo -json $GeoTiff | Set-Content -Path $infoJson -Encoding UTF8
$json = Get-Content -Path $infoJson -Raw -Encoding UTF8 | ConvertFrom-Json
Remove-Item -Path $infoJson -Force -ErrorAction SilentlyContinue
$cc = $json.cornerCoordinates
$coords = @(
    @($cc.upperLeft[0], $cc.upperLeft[1]),
    @($cc.upperRight[0], $cc.upperRight[1]),
    @($cc.lowerRight[0], $cc.lowerRight[1]),
    @($cc.lowerLeft[0], $cc.lowerLeft[1])
)
$coordJson = ($coords | ForEach-Object { "[$($_[0]),$($_[1])]" }) -join ", "

$js = @"
// Generated by Import-GeoTiff.ps1 — do not commit if it contains experiments
(function () {
    var base = window.__SHIMODA_MAP_CONFIG__;
    if (!base || !base.MAP_IMAGE) return;
    base.MAP_IMAGE.url = 'map-qgis.webp';
    base.MAP_IMAGE.cacheVersion = 'local-qgis-' + Date.now();
    base.MAP_IMAGE.coordinates = [$coordJson];
    var lngs = base.MAP_IMAGE.coordinates.map(function (c) { return c[0]; });
    var lats = base.MAP_IMAGE.coordinates.map(function (c) { return c[1]; });
    var minLng = Math.min.apply(null, lngs);
    var maxLng = Math.max.apply(null, lngs);
    var minLat = Math.min.apply(null, lats);
    var maxLat = Math.max.apply(null, lats);
    var padLng = (maxLng - minLng) * 0.2;
    var padLat = (maxLat - minLat) * 0.2;
    base.MAP_IMAGE.maxBounds = [
        [minLng - padLng, minLat - padLat],
        [maxLng + padLng, maxLat + padLat]
    ];
    base.MAP_IMAGE.center = [(minLng + maxLng) / 2, (minLat + maxLat) / 2];
    base.MAP_IMAGE.initCenter = base.MAP_IMAGE.center;
    base.MAP_IMAGE.initCenterMobile = base.MAP_IMAGE.center;
})();
"@

Set-Content -Path $outConfig -Value $js -Encoding UTF8
Write-Host "Wrote $outWebp"
Write-Host "Wrote $outConfig"
Write-Host "Restart Start-Map.ps1 and verify in browser."
